// ============================================================================
// Export Service
// ============================================================================

export class ExportService {
  private svgExporter = new SVGExporter();
  private dxfExporter = new DXFExporter();
  private pdfExporter = new PDFExporter();
  private pngExporter = new PNGExporter();

  async export(
    plan: Plan,
    rooms: Room[],
    objects: PlacedObject[],
    options: ExportOptions,
  ): Promise<ExportResult> {
    try {
      let filePath: string;
      let content: string;

      switch (options.format) {
        case 'svg':
          content = this.svgExporter.generateSVG(plan, rooms, objects, options);
          filePath = await this.saveFile(content, plan.id, 'svg');
          break;

        case 'dxf':
          content = this.dxfExporter.generateDXF(plan, rooms, objects, options);
          filePath = await this.saveFile(content, plan.id, 'dxf');
          break;

        case 'pdf':
          filePath = await this.pdfExporter.generatePDF(plan, rooms, objects, options);
          break;

        case 'png':
          filePath = await this.pngExporter.generatePNG(plan, rooms, objects, options);
          break;

        default:
          throw new Error('Unsupported export format');
      }

      const fileInfo = await RNFS.stat(filePath);

      return {
        success: true,
        filePath,
        fileSize: parseInt(fileInfo.size, 10),
      };
    } catch (error: any) {
      return {
        success: false,
        error: error.message || 'Export failed',
      };
    }
  }

  private async saveFile(
    content: string,
    planId: string,
    extension: string,
  ): Promise<string> {
    const fileName = `plan_${planId}_${Date.now()}.${extension}`;
    const exportsDir = `${RNFS.DocumentDirectoryPath}/${APP_CONFIG.fileSystem.exportsDirectory}`;

    // Create directory if it doesn't exist
    const dirExists = await RNFS.exists(exportsDir);
    if (!dirExists) {
      await RNFS.mkdir(exportsDir);
    }

    const filePath = `${exportsDir}/${fileName}`;
    await RNFS.writeFile(filePath, content, 'utf8');

    return filePath;
  }

  async deleteExport(filePath: string): Promise<boolean> {
    try {
      const exists = await RNFS.exists(filePath);
      if (exists) {
        await RNFS.unlink(filePath);
      }
      return true;
    } catch (error) {
      console.error('Failed to delete export:', error);
      return false;
    }
  }

  async shareExport(filePath: string): Promise<void> {
    // In production, use react-native-share
    // For now, just log
    console.log('Sharing export:', filePath);
  }
}

