import type {Plan, Room, PlacedObject} from '@types/index';
import {APP_CONFIG} from '@utils/constants';

export type ExportFormat = 'pdf' | 'svg' | 'dxf' | 'png';

export interface ExportOptions {
  format: ExportFormat;
  includeGrid?: boolean;
  includeMeasurements?: boolean;
  includeLabels?: boolean;
  scale?: number;
  quality?: 'low' | 'medium' | 'high';
}

export interface ExportResult {
  success: boolean;
  filePath?: string;
  fileSize?: number;
  error?: string;
}

// ============================================================================
// SVG Export
// ============================================================================

class SVGExporter {
  generateSVG(
    plan: Plan,
    rooms: Room[],
    objects: PlacedObject[],
    options: ExportOptions,
  ): string {
    const width = plan.width;
    const height = plan.height;
    const scale = options.scale || plan.scale;

    let svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg"
     width="${width}"
     height="${height}"
     viewBox="0 0 ${width} ${height}">
  <title>${plan.title}</title>
  <desc>Generated by RoomDraft</desc>

  <!-- Background -->
  <rect x="0" y="0" width="${width}" height="${height}" fill="#FFFFFF"/>

`;

    // Add grid if requested
    if (options.includeGrid) {
      svg += this.generateGrid(width, height, 50);
    }

    // Add rooms
    for (const room of rooms) {
      svg += this.generateRoom(room);
    }

    // Add objects
    for (const obj of objects) {
      svg += this.generateObject(obj);
    }

    // Add measurements if requested
    if (options.includeMeasurements) {
      svg += this.generateMeasurements(rooms, scale);
    }

    // Add labels if requested
    if (options.includeLabels) {
      svg += this.generateLabels(rooms, objects);
    }

    svg += '</svg>';
    return svg;
  }

  private generateGrid(width: number, height: number, gridSize: number): string {
    let grid = '  <!-- Grid -->\n  <g id="grid" opacity="0.2">\n';

    for (let x = 0; x <= width; x += gridSize) {
      grid += `    <line x1="${x}" y1="0" x2="${x}" y2="${height}" stroke="#CCCCCC" stroke-width="0.5"/>\n`;
    }

    for (let y = 0; y <= height; y += gridSize) {
      grid += `    <line x1="0" y1="${y}" x2="${width}" y2="${y}" stroke="#CCCCCC" stroke-width="0.5"/>\n`;
    }

    grid += '  </g>\n\n';
    return grid;
  }

  private generateRoom(room: Room): string {
    const walls = JSON.parse(room.walls as any) || [];
    if (walls.length === 0) return '';

    let path = '  <g id="room-' + room.id + '">\n';
    path += `    <title>${room.name}</title>\n`;

    // Draw walls
    for (const wall of walls) {
      path += `    <line x1="${wall.start.x}" y1="${wall.start.y}" x2="${wall.end.x}" y2="${wall.end.y}" stroke="#424242" stroke-width="3"/>\n`;
    }

    path += '  </g>\n\n';
    return path;
  }

  private generateObject(obj: PlacedObject): string {
    const x = obj.positionX;
    const y = obj.positionY;
    const w = obj.width * 100; // Convert to pixels
    const h = obj.depth * 100;
    const rotation = obj.rotation;

    return `  <rect x="${x - w / 2}" y="${y - h / 2}" width="${w}" height="${h}"
            fill="#8D6E63" opacity="0.5"
            transform="rotate(${rotation} ${x} ${y})"/>\n`;
  }

  private generateMeasurements(rooms: Room[], scale: number): string {
    let measurements = '  <!-- Measurements -->\n  <g id="measurements">\n';

    for (const room of rooms) {
      const areaInMeters = room.area;
      const centerX = 500; // Simplified - should calculate actual center
      const centerY = 500;

      measurements += `    <text x="${centerX}" y="${centerY}"
                           text-anchor="middle"
                           font-size="14"
                           fill="#000000">
                           ${areaInMeters.toFixed(2)}m²
                      </text>\n`;
    }

    measurements += '  </g>\n\n';
    return measurements;
  }

  private generateLabels(rooms: Room[], objects: PlacedObject[]): string {
    let labels = '  <!-- Labels -->\n  <g id="labels">\n';

    for (const room of rooms) {
      const centerX = 500; // Simplified
      const centerY = 480;

      labels += `    <text x="${centerX}" y="${centerY}"
                        text-anchor="middle"
                        font-size="16"
                        font-weight="bold"
                        fill="#000000">
                        ${room.name}
                   </text>\n`;
    }

    labels += '  </g>\n\n';
    return labels;
  }
}

