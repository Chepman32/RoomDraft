// DXF Export (CAD Format)
// ============================================================================

class DXFExporter {
  generateDXF(
    plan: Plan,
    rooms: Room[],
    objects: PlacedObject[],
    options: ExportOptions,
  ): string {
    let dxf = this.generateHeader();

    dxf += this.generateTables();

    // Entities section
    dxf += '0\nSECTION\n2\nENTITIES\n';

    // Add rooms as polylines
    for (const room of rooms) {
      dxf += this.generateRoomEntity(room);
    }

    // Add objects as blocks
    for (const obj of objects) {
      dxf += this.generateObjectEntity(obj);
    }

    dxf += '0\nENDSEC\n';

    dxf += '0\nEOF\n';
    return dxf;
  }

  private generateHeader(): string {
    return `0
SECTION
2
HEADER
9
$ACADVER
1
AC1015
9
$INSUNITS
70
4
0
ENDSEC
`;
  }

  private generateTables(): string {
    return `0
SECTION
2
TABLES
0
TABLE
2
LAYER
70
1
0
LAYER
2
WALLS
70
0
62
7
6
CONTINUOUS
0
LAYER
2
OBJECTS
70
0
62
3
6
CONTINUOUS
0
ENDTAB
0
ENDSEC
`;
  }

  private generateRoomEntity(room: Room): string {
    const walls = JSON.parse(room.walls as any) || [];
    if (walls.length === 0) return '';

    let entity = '';

    for (const wall of walls) {
      entity += `0
LINE
8
WALLS
10
${wall.start.x * 0.001}
20
${wall.start.y * 0.001}
11
${wall.end.x * 0.001}
21
${wall.end.y * 0.001}
`;
    }

    return entity;
  }

  private generateObjectEntity(obj: PlacedObject): string {
    const x = obj.positionX * 0.001;
    const y = obj.positionY * 0.001;
    const w = obj.width;
    const h = obj.depth;

    return `0
INSERT
8
OBJECTS
2
${obj.type}
10
${x}
20
${y}
41
${w}
42
${h}
50
${obj.rotation}
`;
  }
}

